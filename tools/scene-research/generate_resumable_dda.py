#!/usr/bin/env python3
"""Mechanically derive a resumable experiment from the authoritative DDA body."""
import hashlib, re, sys
from pathlib import Path
root = Path(__file__).resolve().parents[2]
source = (root / 'crates/voxy_render/src/archive_depth_dda_paired.wgsl').read_text()
marker = 'fn trace_depth_dda_paired('
fn = source[source.index(marker):]
assert fn.count('fn ') == 1
init, loop = fn.split(' for(var step=0u;step<u32(size.x+size.y+4);step++) {', 1)
init = init[init.index('{')+1:]
assert loop.endswith(' }\n return precise_miss(visited);\n}\n')
loop = loop[:-len(' }\n return precise_miss(visited);\n}\n')]
fields = {
 'begin':'DdaVectorPair','end':'DdaVectorPair','size':'vec2<i32>','delta':'DdaVectorPair','high':'vec2<f32>',
 'cell':'vec2<i32>','entry':'vec2<f32>','visited':'u32','checked_tile':'vec2<i32>','hierarchy_level':'i32',
 'dx':'vec2<f32>','dy':'vec2<f32>','dz':'vec2<f32>','bx':'vec2<f32>','by':'vec2<f32>','bz':'vec2<f32>',
 'rejection_ray':'DdaIntervalRay','z_begin_interval':'DdaInterval','z_delta_interval':'DdaInterval',
 'positive_x':'bool','positive_y':'bool','direction':'vec2<i32>','cached_entry_z':'vec2<f32>',
 'cached_depth_bits':'u32','cached_parameter':'vec2<f32>','cached_cell':'vec2<i32>','cached_x':'vec2<f32>','cached_y':'vec2<f32>'}
init = init.replace('return precise_miss(0u);','return dda_cursor_finished(precise_miss(0u));')
result = '// Generated by generate_resumable_dda.py; experiment only.\n// Original SHA256: ' + hashlib.sha256(source.encode()).hexdigest() + '\n'
result += 'struct DdaCursor {\n' + ''.join(f' {key}:{ty},\n' for key,ty in fields.items()) + ' step:u32,done:bool,hit:DepthDdaPairHit,\n}\n'
result += 'fn dda_cursor_finished(hit:DepthDdaPairHit)->DdaCursor {var s:DdaCursor;s.done=true;s.hit=hit;return s;}\n'
result += 'fn dda_cursor_init(image:texture_2d<f32>,begin:DdaVectorPair,end:DdaVectorPair)->DdaCursor {\n' + init + '\n var s:DdaCursor;\n'
result += ''.join(f' s.{key}={key};\n' for key in fields) + ' s.hit=precise_miss(0u);return s;\n}\n'
# Replace only exits of the outer iteration; inner cell/ancestor loops retain
# their original continue/break operations and exact arithmetic ordering.
assert loop.count('if jumped {continue;}') == 1
loop = loop.replace('if jumped {continue;}','if jumped {return;}')
assert loop.count('if any(cell<vec2<i32>(0))||any(cell>=size){break;}') == 1
loop = loop.replace('if any(cell<vec2<i32>(0))||any(cell>=size){break;}','if any(cell<vec2<i32>(0))||any(cell>=size){(*s).done=true;(*s).hit=precise_miss(visited);return;}')
assert loop.count('if precise_le(high,exit){break;}') == 1
loop = loop.replace('if precise_le(high,exit){break;}','if precise_le(high,exit){(*s).done=true;(*s).hit=precise_miss(visited);return;}')
loop = re.sub(r'return (start_hit|touch|closest|precise_miss\(visited\));',r'(*s).done=true;(*s).hit=\1;return;',loop)
# The longest identifiers are replaced first; word boundaries avoid changing
# precise_axis etc. No operation or operand is changed by state extraction.
loop = re.sub(r'(?<!\.)\b('+'|'.join(sorted(fields,key=len,reverse=True))+r')\b',lambda m:'(*s).'+m[0],loop)
result += 'fn dda_cursor_step(image:texture_2d<f32>,s:ptr<function,DdaCursor>) {\n if (*s).done{return;}\n if (*s).step>=u32((*s).size.x+(*s).size.y+4){(*s).done=true;(*s).hit=precise_miss((*s).visited);return;}\n (*s).step+=1u;\n' + loop + '\n}\n'
path = root / 'crates/voxy_render/src/archive_depth_dda_resumable.wgsl'
if '--check' in sys.argv:
 assert path.read_text() == result, 'resumable experiment drifted from original DDA'
 print('resumable DDA mechanically matches current original source')
else:
 path.write_text(result)
