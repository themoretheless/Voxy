#!/usr/bin/env python3
"""Keep source products and both ray-origin words until after cancellation."""
from pathlib import Path
import sys
root = Path(__file__).resolve().parents[2]
path = root/'crates/voxy_render/src/world_origin_expansion.wgsl'
lines = ['// Generated by generate_world_origin_expansion.py; no intermediate world rounding.',
         'struct WorldExpansionCoordinate {pair:vec2<f32>,bounds:WorldInterval}',
         '// Restricted EFT domain: input products have no subnormal residuals; addends',
         '// have a common exact grid >=2^-103 and sums cannot overflow f32.',
         'fn world_add_domain(v:f32)->bool {let b=bitcast<u32>(v)&0x7fffffffu;return b==0u||(b>=0x17800000u&&b<=0x67800000u);}',
         'fn world_mul_domain(v:f32)->bool {let b=bitcast<u32>(v)&0x7fffffffu;return b==0u||(b>=0x30800000u&&b<=0x4e800000u);}',
         'fn world_dot4_minus_origin(a:vec4<f32>,b:vec4<f32>,origin:vec2<f32>)->WorldExpansionCoordinate {',
         ' var certified=1u;']
lines += [f' var term_{k}=0.;' for k in range(10)]
length = 0
for component in 'xyzw':
    lines += [' {', f'  certified &= select(0u,1u,world_mul_domain(a.{component})&&world_mul_domain(b.{component}));', f'  let product=projection_mul_scalar(a.{component},b.{component});',
              f'  let residual=fma(a.{component},b.{component},-product);']
    for part in ['product', 'residual']:
        lines += ['  {', f'   var carry={part};']
        for k in range(length):
            lines += [f'   certified &= select(0u,1u,world_add_domain(carry)&&world_add_domain(term_{k}));', f'   let sum_{k}=projection_two_sum(carry,term_{k});term_{k}=sum_{k}.y;carry=sum_{k}.x;']
        lines += [f'   term_{length}=carry;', '  }']
        length += 1
    lines += [' }']
for part in ['-origin.x', '-origin.y']:
    lines += [' {', f'  var carry={part};']
    for k in range(length):
        lines += [f'  certified &= select(0u,1u,world_add_domain(carry)&&world_add_domain(term_{k}));', f'  let sum_{k}=projection_two_sum(carry,term_{k});term_{k}=sum_{k}.y;carry=sum_{k}.x;']
    lines += [f'  term_{length}=carry;', ' }']
    length += 1
lines += [' var result=vec2<f32>(0.);']
lines += [f' result=projection_pair_add(result,vec2<f32>(term_{k},0.));' for k in reversed(range(10))]
lines += [' var bounds=wi_scalar(0.);']
for k in reversed(range(10)):
    lines += [f' certified &= select(0u,1u,world_add_domain(term_{k}));',
              f' bounds=wi_add(bounds,wi_scalar(term_{k}));']
lines += [' bounds.valid &= certified;', ' return WorldExpansionCoordinate(result,bounds);', '}']
source = '\n'.join(lines)+'\n'
if '--check' in sys.argv:
    if path.read_text() != source:
        raise SystemExit('world-origin expansion is stale')
else:
    path.write_text(source)
