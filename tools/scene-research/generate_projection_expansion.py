#!/usr/bin/env python3
"""Generate scalar-slot WGSL with the original growing-expansion operation order."""
from pathlib import Path
import sys
ROOT=Path(__file__).resolve().parents[2]
PATH=ROOT/'crates/voxy_render/src/archive_projection_pair.wgsl'
MARKER='// Exact growing expansion'
def function(name,rows):
    count=len(rows)*8
    arguments='a:vec4<f32>,b:vec4<f32>' if len(rows)==1 else 'a:vec4<f32>,b:vec4<f32>,point:vec4<f32>'
    result=[f'fn {name}({arguments})->vec2<f32> {{']
    result += [f' var term_{i}=0.;' for i in range(count)]
    length=0
    for left,right in rows:
        for component in 'xyzw':
            result += [' {',f'  let product=projection_mul_scalar({left}.{component},{right}.{component});',f'  let residual=fma({left}.{component},{right}.{component},-product);']
            for part in ['product','residual']:
                result += ['  {',f'   var carry={part};']
                for index in range(length):
                    result += [f'   let sum_{index}=projection_two_sum(carry,term_{index});term_{index}=sum_{index}.y;carry=sum_{index}.x;']
                result += [f'   term_{length}=carry;','  }']
                length+=1
            result += [' }']
    result += [' var result=vec2<f32>(0.);']
    result += [f' result=projection_pair_add(result,vec2<f32>(term_{i},0.));' for i in reversed(range(count))]
    result += [' return result;','}']
    return '\n'.join(result)
source=PATH.read_text()
if MARKER not in source:
    raise SystemExit('missing expansion boundary')
prefix=source.split(MARKER)[0]
suffix='''// Exact growing expansion, generated by generate_projection_expansion.py.
// Scalar slots preserve every operation and its order while removing dynamic
// private-array indexing. Admission still requires byte-for-byte GPU proof.
'''
suffix+=function('projection_dot4_expanded',[('a','b')])+'\n'
suffix+=function('projection_dot_rows_expanded',[('a','point'),('b','point')])+'\n'
generated=prefix+suffix
if '--check' in sys.argv:
    if source!=generated:
        raise SystemExit('projection expansion is stale')
else:
    PATH.write_text(generated)
