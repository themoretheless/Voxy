//! Direct CPU generation into Apple unified buffers, with ordered staging fallback.
use crate::{ComputeError, ComputeMemoryBudget, ComputeStorage, ManagedBufferDescriptor};
use std::sync::{
    Arc,
    atomic::{AtomicU8, AtomicUsize, Ordering},
};

const PENDING: u8 = 0;
const READY: u8 = 1;
const ENCODING: u8 = 2;
const FAILED: u8 = 3;

#[derive(Debug)]
struct Slot {
    buffer: Arc<ComputeStorage>,
    state: Arc<AtomicU8>,
}

// Deferred mapping callbacks are dropped when their encoder/command buffer is
// discarded. Re-map that unused slot instead of permanently losing ring capacity.
struct ReclaimDiscarded {
    buffer: wgpu::Buffer,
    state: Arc<AtomicU8>,
    completed: bool,
}
impl Drop for ReclaimDiscarded {
    fn drop(&mut self) {
        if !self.completed {
            let state = self.state.clone();
            self.buffer
                .slice(..)
                .map_async(wgpu::MapMode::Write, move |result| {
                    state.store(
                        if result.is_ok() { READY } else { FAILED },
                        Ordering::Release,
                    );
                });
        }
    }
}

/// A format-independent copy from a generated staging snapshot into a target.
#[derive(Clone, Copy, Debug)]
pub struct SharedUploadCopy<'a> {
    pub source_offset: u64,
    pub target: &'a wgpu::Buffer,
    pub target_offset: u64,
    pub size: u64,
}

/// Three independently mapped primary buffers for transient CPU-produced inputs.
///
/// A slot is leased to exactly one command encoder, then mapped back only after
/// that encoder is submitted and the GPU finishes using it. Exhaustion never
/// waits for an unsubmitted encoder: `encode` returns false for caller fallback.
/// Discarding an unsubmitted encoder asynchronously reclaims its unused slot.
/// The ring participates in the device's managed memory budget and retirement.
#[derive(Debug)]
pub struct SharedUploadRing {
    device: wgpu::Device,
    slots: Vec<Slot>,
    next_generated_slot: AtomicUsize,
}
/// Immutable generated bytes. Clones retained by each encoder prevent recycling
/// until both the current CPU snapshot and every submitted/cancelled use retire.
#[derive(Clone, Debug)]
pub struct SharedUploadSnapshot(Arc<SnapshotInner>);
#[derive(Debug)]
struct SnapshotInner {
    buffer: wgpu::Buffer,
    shared: Option<Arc<AtomicU8>>,
    // Retain managed ownership as well as the wgpu handle until all uses retire.
    _storage: Option<Arc<ComputeStorage>>,
    size: u64,
}
impl Drop for SnapshotInner {
    fn drop(&mut self) {
        if let Some(state) = &self.shared {
            let state = state.clone();
            self.buffer
                .slice(..)
                .map_async(wgpu::MapMode::Write, move |result| {
                    state.store(
                        if result.is_ok() { READY } else { FAILED },
                        Ordering::Release,
                    );
                });
        }
    }
}
impl SharedUploadSnapshot {
    /// Whether consumers bind the generated primary allocation without a copy.
    pub fn is_direct(&self) -> bool {
        self.0.shared.is_some()
    }

    /// Bind only through this method, once per consuming encoder. Overflow copies
    /// precede consumers in that encoder. Discarded callbacks release their lease.
    pub fn buffer_for_encoder(
        &self,
        encoder: &mut wgpu::CommandEncoder,
        legacy: &wgpu::Buffer,
    ) -> wgpu::Buffer {
        // Snapshots can only be constructed on Apple Silicon. Keep the native
        // completion capture out of WebGPU builds, whose handles are not Send.
        #[cfg(all(target_os = "macos", target_arch = "aarch64"))]
        {
            let retained = self.clone();
            encoder.on_submitted_work_done(move || drop(retained));
        }
        if self.0.shared.is_some() {
            self.0.buffer.clone()
        } else {
            encoder.copy_buffer_to_buffer(&self.0.buffer, 0, legacy, 0, self.0.size);
            legacy.clone()
        }
    }
}
// A failed or panicking producer has no GPU consumers. Release its mapped view
// before this guard unmaps and returns the slot to the asynchronous ready pool.
struct Preparing(Option<SnapshotInner>);
impl Drop for Preparing {
    fn drop(&mut self) {
        if let Some(inner) = self.0.take() {
            inner.buffer.unmap();
            drop(inner);
        }
    }
}
impl SharedUploadRing {
    /// Returns None outside Apple Silicon Metal, without primary mapping support,
    /// or if extra ring memory cannot be admitted. The legacy path remains usable.
    pub fn new(device: &wgpu::Device, size: u64, usage: wgpu::BufferUsages) -> Option<Self> {
        if !is_apple_metal(device)
            || !device
                .features()
                .contains(wgpu::Features::MAPPABLE_PRIMARY_BUFFERS)
            || usage.intersects(wgpu::BufferUsages::MAP_READ | wgpu::BufferUsages::MAP_WRITE)
        {
            return None;
        }
        let descriptors = [ManagedBufferDescriptor {
            label: "Apple shared transient input",
            size,
            contents: None,
            usage: usage | wgpu::BufferUsages::MAP_WRITE,
        }; 3];
        let buffers = ComputeMemoryBudget::for_device(device)
            .allocate_buffer_batch(&descriptors)
            .ok()?;
        let slots = buffers
            .into_iter()
            .map(|buffer| {
                let state = Arc::new(AtomicU8::new(PENDING));
                let ready = state.clone();
                buffer
                    .slice(..)
                    .map_async(wgpu::MapMode::Write, move |result| {
                        ready.store(
                            if result.is_ok() { READY } else { FAILED },
                            Ordering::Release,
                        );
                    });
                Slot {
                    buffer: Arc::new(buffer),
                    state,
                }
            })
            .collect();
        Some(Self {
            device: device.clone(),
            slots,
            next_generated_slot: AtomicUsize::new(0),
        })
    }

    /// Generate final shader bytes once, without a CPU snapshot. A producer error
    /// publishes nothing; ready slots are reclaimed even during unwinding. Busy
    /// rings use a unique mapped staging snapshot with ordered copies at consume.
    /// `size` is the initialized prefix, positive and COPY_BUFFER_ALIGNMENT aligned.
    pub fn prepare<E>(
        &self,
        size: u64,
        produce: impl FnOnce(wgpu::WriteOnly<'_, [u8]>) -> Result<(), E>,
    ) -> Result<SharedUploadSnapshot, E>
    where
        E: From<ComputeError>,
    {
        if size == 0
            || size > self.slots[0].buffer.size()
            || !size.is_multiple_of(wgpu::COPY_BUFFER_ALIGNMENT)
        {
            return Err(ComputeError::InvalidBuffer.into());
        }
        self.device
            .poll(wgpu::PollType::Poll)
            .map_err(|e| E::from(ComputeError::Validation(e.to_string())))?;
        // Spread successive generated snapshots across the resident allocations.
        // READY is still acquired atomically: rotation never permits recycling a
        // snapshot retained by the CPU or by an outstanding/cancelled encoder.
        let start = self.next_generated_slot.fetch_add(1, Ordering::Relaxed) % self.slots.len();
        let slot = (0..self.slots.len())
            .map(|offset| &self.slots[(start + offset) % self.slots.len()])
            .find(|slot| {
                slot.state
                    .compare_exchange(READY, ENCODING, Ordering::AcqRel, Ordering::Acquire)
                    .is_ok()
            });
        let (buffer, shared, storage) = if let Some(slot) = slot {
            (
                (*slot.buffer).clone(),
                Some(slot.state.clone()),
                Some(slot.buffer.clone()),
            )
        } else {
            (
                self.device.create_buffer(&wgpu::BufferDescriptor {
                    label: Some("generated input overflow snapshot"),
                    size,
                    usage: wgpu::BufferUsages::MAP_WRITE | wgpu::BufferUsages::COPY_SRC,
                    mapped_at_creation: true,
                }),
                None,
                None,
            )
        };
        let mut pending = Preparing(Some(SnapshotInner {
            buffer,
            shared,
            _storage: storage,
            size,
        }));
        {
            let mut mapped = pending
                .0
                .as_ref()
                .unwrap()
                .buffer
                .slice(..size)
                .get_mapped_range_mut()
                .map_err(|e| E::from(ComputeError::Mapping(e.to_string())))?;
            produce(mapped.slice(..))?;
        }
        let inner = pending.0.take().unwrap();
        inner.buffer.unmap();
        Ok(SharedUploadSnapshot(Arc::new(inner)))
    }

    /// Bytes charged to the shared device budget by all ring slots. Retired
    /// slots remain charged according to ComputeMemoryBudget's cleanup policy.
    pub fn allocation_bytes(&self) -> u64 {
        self.slots.iter().map(|slot| slot.buffer.size()).sum()
    }

    /// The returned buffer may be consumed later in this same encoder only.
    /// Remapping is deferred until the complete command buffer finishes. Overflow
    /// records a unique staging snapshot before consumers, preserving queue order.
    /// `legacy` must belong to this device, match the ring's size and allow COPY_DST.
    /// The index is a cached slot index, or buffers().count() for the legacy target.
    pub fn write_or_stage(
        &self,
        encoder: &mut wgpu::CommandEncoder,
        legacy: &wgpu::Buffer,
        produce: impl Fn(wgpu::WriteOnly<'_, [u8]>),
    ) -> Result<(usize, wgpu::Buffer), ComputeError> {
        let mut selected = None;
        if self.encode(encoder, &produce, |index, buffer, _| {
            selected = Some((index, buffer.clone()))
        })? {
            return Ok(selected.unwrap());
        }
        self.stage_legacy(encoder, legacy, produce)?;
        Ok((3, legacy.clone()))
    }

    /// Generate an immutable staging snapshot and copy it into a persistent
    /// legacy target in this encoder. Used for retained external binding ABIs.
    /// Target must belong to this device and allow COPY_DST. Transient staging
    /// is outside ComputeMemoryBudget's existing resident-storage accounting.
    pub fn stage_legacy(
        &self,
        encoder: &mut wgpu::CommandEncoder,
        legacy: &wgpu::Buffer,
        produce: impl Fn(wgpu::WriteOnly<'_, [u8]>),
    ) -> Result<(), ComputeError> {
        self.stage_copy_plan(
            encoder,
            legacy.size(),
            produce,
            &[SharedUploadCopy {
                source_offset: 0,
                target: legacy,
                target_offset: 0,
                size: legacy.size(),
            }],
        )
    }

    /// Stage one ring-sized, generated snapshot into several buffers/ranges.
    /// Consumers must follow these copies in this encoder. All ranges and target
    /// usages are validated before running the producer or recording any copy.
    /// Staging follows the same transient accounting policy as stage_legacy.
    pub fn stage_copies(
        &self,
        encoder: &mut wgpu::CommandEncoder,
        produce: impl Fn(wgpu::WriteOnly<'_, [u8]>),
        copies: &[SharedUploadCopy<'_>],
    ) -> Result<(), ComputeError> {
        self.stage_copy_plan(encoder, self.slots[0].buffer.size(), produce, copies)
    }

    fn stage_copy_plan(
        &self,
        encoder: &mut wgpu::CommandEncoder,
        size: u64,
        produce: impl Fn(wgpu::WriteOnly<'_, [u8]>),
        copies: &[SharedUploadCopy<'_>],
    ) -> Result<(), ComputeError> {
        if copies.is_empty()
            || copies.iter().any(|copy| {
                copy.size == 0
                    || !copy.size.is_multiple_of(wgpu::COPY_BUFFER_ALIGNMENT)
                    || !copy
                        .source_offset
                        .is_multiple_of(wgpu::COPY_BUFFER_ALIGNMENT)
                    || !copy
                        .target_offset
                        .is_multiple_of(wgpu::COPY_BUFFER_ALIGNMENT)
                    || copy
                        .source_offset
                        .checked_add(copy.size)
                        .is_none_or(|end| end > size)
                    || copy
                        .target_offset
                        .checked_add(copy.size)
                        .is_none_or(|end| end > copy.target.size())
                    || !copy.target.usage().contains(wgpu::BufferUsages::COPY_DST)
            })
        {
            return Err(ComputeError::InvalidBuffer);
        }
        let staging = self.device.create_buffer(&wgpu::BufferDescriptor {
            label: Some("transient input overflow staging"),
            size,
            usage: wgpu::BufferUsages::MAP_WRITE | wgpu::BufferUsages::COPY_SRC,
            mapped_at_creation: true,
        });
        {
            let mut mapped = staging
                .slice(..)
                .get_mapped_range_mut()
                .map_err(|e| ComputeError::Validation(e.to_string()))?;
            produce(mapped.slice(..));
        }
        staging.unmap();
        for copy in copies {
            encoder.copy_buffer_to_buffer(
                &staging,
                copy.source_offset,
                copy.target,
                copy.target_offset,
                copy.size,
            );
        }
        Ok(())
    }

    /// Stable slot buffers for prebuilt bindings. They may only be consumed in
    /// an encoder that has leased that slot via encode or write_or_stage;
    /// mapping and subsequent submissions remain owned by this ring.
    pub fn buffers(&self) -> impl Iterator<Item = &wgpu::Buffer> {
        self.slots.iter().map(|slot| &**slot.buffer)
    }

    /// Produce the complete input directly into shared memory and encode its
    /// consumers. `consume` must use the buffer only in this encoder, and must
    /// not retain it for another submission. No API mapping may escape `produce`.
    /// Returns false without invoking either closure when all slots are busy.
    /// Producers must initialize every byte their consumers read on every call.
    pub fn encode(
        &self,
        encoder: &mut wgpu::CommandEncoder,
        produce: impl FnOnce(wgpu::WriteOnly<'_, [u8]>),
        consume: impl FnOnce(usize, &wgpu::Buffer, &mut wgpu::CommandEncoder),
    ) -> Result<bool, ComputeError> {
        // Poll only; never serialize the frame with a device-wide wait.
        self.device
            .poll(wgpu::PollType::Poll)
            .map_err(|e| ComputeError::Validation(e.to_string()))?;
        let Some((index, slot)) = self.slots.iter().enumerate().find(|(_, slot)| {
            slot.state
                .compare_exchange(READY, ENCODING, Ordering::AcqRel, Ordering::Acquire)
                .is_ok()
        }) else {
            return Ok(false);
        };
        {
            let mut mapped = slot
                .buffer
                .slice(..)
                .get_mapped_range_mut()
                .map_err(|e| ComputeError::Validation(e.to_string()))?;
            produce(mapped.slice(..));
        }
        slot.buffer.unmap();
        consume(index, &slot.buffer, encoder);
        let mut reclaim = ReclaimDiscarded {
            buffer: (*slot.buffer).clone(),
            state: slot.state.clone(),
            completed: false,
        };
        slot.state.store(PENDING, Ordering::Release);
        encoder.map_buffer_on_submit(&slot.buffer, wgpu::MapMode::Write, .., move |result| {
            reclaim.completed = true;
            reclaim.state.store(
                if result.is_ok() { READY } else { FAILED },
                Ordering::Release,
            );
        });
        Ok(true)
    }
}

#[cfg(all(target_os = "macos", target_arch = "aarch64"))]
fn is_apple_metal(device: &wgpu::Device) -> bool {
    let info = device.adapter_info();
    info.backend == wgpu::Backend::Metal
        && info.device_type == wgpu::DeviceType::IntegratedGpu
        && info.name.starts_with("Apple M")
}
#[cfg(not(all(target_os = "macos", target_arch = "aarch64")))]
fn is_apple_metal(_: &wgpu::Device) -> bool {
    false
}

